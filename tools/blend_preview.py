"""Blend preview: lay feature materials side by side on one plane and blend
them the way the game's terrain does, to judge the transitions.

    python tools/blend_preview.py out/blend_test A.json B.json [C.json ...]
        [--tiles 3] [--depth 0.12] [--wiggle 0.25] [--size 4096] [--export] [--open]

Each material is a text project exported with the "Game material (features)"
template (`<name>_ColorHeight.png` + `<name>.material.json`, by default in
`<project dir>/export`; `--export` makes them with the running app first).
They become zones along X, left to right, in the order given. Splat weights
fade between neighbouring zones with a noisy edge, then every pixel is
blended with the game's rule (terrain.wgsl, blendWeights): each surface lifts
by `height * 0.5 + weight`, and every surface within `depth` of the highest
shares the pixel by how far above that line it stands. So rocks poke through
a neighbour's dirt, dirt fills the cracks of a rock bed, and nothing fades
through like a plain crossfade.

The result is a normal text project (`blend.mat` drives one fill layer):
edit the script's numbers (depth, splat widths, wiggle) and it live-reloads.
Colour is each material's exported, pre-grade colour; height is scaled by
each material's relief_m so mixed reliefs compare in metres.
"""

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
MP = REPO / "target" / "debug" / ("mp.exe" if sys.platform == "win32" else "mp")


def mp(*args):
    r = subprocess.run([str(MP), *args], capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(f"mp {' '.join(args)} failed:\n{r.stdout}{r.stderr}")
    return r.stdout


def script(names, reliefs, tiles, depth, wiggle, size):
    n = len(names)
    top = max(reliefs)
    lines = [
        f"# Blend preview of {n} materials along X (generated by tools/blend_preview.py).",
        "# Splat weights per zone, then the game's height blend (terrain.wgsl blendWeights).",
        f"size {size}",
        "",
        f"# The game's blend depth (terrain look.y): how far below the highest lift",
        f"# a surface still shows. Smaller = harder, more height-driven edges.",
        f"depth = {depth}",
        "",
        "# Position along the strip, wiggled so zone edges aren't straight lines.",
        f"x = gradient() + (noise(perlin, scale=4, octaves=4, seed=7) - 0.5) * {wiggle}",
        "",
    ]
    for k, name in enumerate(names):
        f = f"materials/{name}_ColorHeight.png"
        lines += [
            f"# {name}: relief {reliefs[k]} m, {tiles} tiles across",
            f"col{k} = bitmap(image=\"{f}\", repeat={tiles})",
            f"h{k}   = bitmap(image=\"{f}\", repeat={tiles}) | grayscale(alpha)",
            # Triangle splat centred on the zone, overlapping its neighbours.
            f"w{k}   = clamp01(1.6 - math(x, b={(k + 0.5) / n:.4f}, op=difference) * {n * 1.6:.3f})",
            f"lift{k} = h{k} * 0.5 + w{k}",
            "",
        ]
    top_expr = "lift0"
    for k in range(1, n):
        top_expr = f"max({top_expr}, lift{k})"
    lines += [f"top = {top_expr}", ""]
    for k in range(n):
        lines.append(f"b{k} = max(lift{k} - top + depth, 0)")
    lines.append("sum = " + " + ".join(f"b{k}" for k in range(n)) + " + 0.0001")
    for k in range(n):
        lines.append(f"n{k} = b{k} / sum")
    lines += ["", "# Colour: each surface over the ones before it by its share of what's shown so far."]
    lines.append("color0 = col0")
    for k in range(1, n):
        so_far = " + ".join(f"n{j}" for j in range(k + 1))
        lines.append(f"color{k} = mix(color{k - 1}, col{k}, n{k} / ({so_far} + 0.0001))")
    height = " + ".join(f"n{k} * h{k} * {reliefs[k] / top:.3f}" for k in range(n))
    lines += [
        "",
        f"output base_color = color{n - 1}",
        f"output height = {height}",
        "output roughness = 0.8",
        "",
        "# Debug (mp script_step step=weights): the blended shares as flat colours,",
        "# zone 0 red, 1 green, 2 blue, 3 yellow.",
    ]
    flat = ["#d04030", "#40b040", "#3060d0", "#d0c040"]
    lines.append(f"weights0 = color(color={flat[0]})")
    for k in range(1, n):
        so_far = " + ".join(f"n{j}" for j in range(k + 1))
        lines.append(f"weights{k} = mix(weights{k - 1}, {flat[k]}, n{k} / ({so_far} + 0.0001))")
    lines += [f"weights = weights{n - 1}", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("out", type=Path, help="folder for the blend project")
    ap.add_argument("projects", type=Path, nargs="+", help="material projects (.json), left to right")
    ap.add_argument("--tiles", type=int, default=3, help="material tiles across the plane (default 3)")
    ap.add_argument("--depth", type=float, default=0.12, help="blend depth, the game's look.y (default 0.12)")
    ap.add_argument("--wiggle", type=float, default=0.25, help="zone edge noise (default 0.25)")
    ap.add_argument("--size", type=int, default=4096, help="preview texture size (default 4096)")
    ap.add_argument("--export", action="store_true", help="export each material with the running app first")
    ap.add_argument("--open", action="store_true", help="open the blend project in the running app")
    a = ap.parse_args()
    if not 2 <= len(a.projects) <= 4:
        sys.exit("give 2 to 4 material projects")

    out = a.out.resolve()
    name = out.name
    data = out / f"{name}.data"
    (data / "materials").mkdir(parents=True, exist_ok=True)
    (data / "scripts").mkdir(exist_ok=True)

    names, reliefs = [], []
    for p in a.projects:
        p = p.resolve()
        stem = p.stem
        export = p.parent / "export"
        if a.export:
            mp("open_project", f"path={p}")
            mp("export_textures", f"folder={export}", "preset=Game material (features)", "size=2048")
        manifest = export / f"{stem}.material.json"
        color = export / f"{stem}_ColorHeight.png"
        if not manifest.exists() or not color.exists():
            sys.exit(f"{stem}: no game export in {export} (run with --export)")
        m = json.loads(manifest.read_text())
        shutil.copyfile(color, data / "materials" / color.name)
        names.append(stem)
        reliefs.append(float(m.get("relief_m", 0.1)))
        mesh = p.parent / f"{stem}.data" / "mesh"
        if not (data / "mesh").exists() and mesh.exists():
            shutil.copytree(mesh, data / "mesh")

    (data / "scripts" / "blend.mat").write_text(script(names, reliefs, a.tiles, a.depth, a.wiggle, a.size))

    # The project: the first material's plane and view, one fill driven by the script.
    first = json.loads(a.projects[0].resolve().read_text())
    ts = first["texture_sets"][0]
    layer = ts["layers_bottom_to_top"][0]
    layer.update(id=1, name="Blend", mask=None, feature=None)
    layer["images"] = [None] * 6
    fill = layer["content"]["fill"]
    fill.update(graph=1, height_blend=0.0, tiling=1.0)
    ts["layers_bottom_to_top"] = [layer]
    ts.pop("features", None)
    ts["selected"] = 0
    first["graphs"] = [{"id": 1, "graph": {"name": "Blend", "script_file": "scripts/blend.mat"}}]
    path = out / f"{name}.json"
    path.write_text(json.dumps(first, indent=1))
    print(path)
    if a.open:
        mp("open_project", f"path={path}")


if __name__ == "__main__":
    main()
